import { TRPCError } from "@trpc/server";
import type { z } from "zod";
import {
  type programCalendarWrite,
  type programCalendarRemove,
} from "~/lib/program-calendar";
import {
  inTransaction,
  lockEntity,
  type DomainDb,
} from "~/server/transactions";
import { ensureSessionPlanningWindow, lockSessionPlanning } from "~/server/session-planning";
import { tutoringPauseSemanticRanges } from "~/lib/tutoring-policy";
import { assertCalendarPolicyHistoryIntegrity } from "./calendar-policy-history";

async function lockCalendarPolicy(tx: Parameters<typeof lockSessionPlanning>[0], date: string) {
  // Different, overlapping ranges share the same fence as publication and attendance.
  await lockEntity(tx, "program:period");
  await lockSessionPlanning(tx);
  await assertCalendarPolicyHistoryIntegrity(tx);
  await lockEntity(tx, `program-calendar:${date}`);
}

function pauseMeaning(row: Parameters<typeof tutoringPauseSemanticRanges>[0][number] | null) {
  return JSON.stringify(tutoringPauseSemanticRanges(row ? [row] : []));
}

/** A tombstone keeps the version monotonic: remove/recreate never revives a stale editor. */
export async function saveProgramCalendar(
  db: DomainDb,
  input: z.infer<typeof programCalendarWrite>,
) {
  return inTransaction(db, async (tx) => {
    await lockCalendarPolicy(tx, input.date);
    const current = await tx.programCalendarDay.findUnique({
      where: { date: input.date },
    });
    if ((current?.version ?? 0) !== input.expectedVersion)
      throw new TRPCError({
        code: "CONFLICT",
        message: "The tutoring notice changed. Reload before saving.",
      });
    const schedulingEffect = input.schedulingEffect ?? current?.schedulingEffect ?? "NOTICE";
    const saved = await tx.programCalendarDay.upsert({
      where: { date: input.date },
      create: {
        date: input.date,
        endDate: input.endDate,
        reason: input.reason,
        schedulingEffect,
      },
      update: {
        endDate: input.endDate,
        reason: input.reason,
        schedulingEffect,
        active: true,
        version: { increment: 1 },
      },
    });
    // Apply policy and its future commitments together; ordinary cancellation notices
    // are generated by the scheduler using the same transaction and captured rosters.
    if (pauseMeaning(current) !== pauseMeaning(saved)) {
      const revision = await tx.programCalendarPolicyRevision.findFirstOrThrow({ where: { date: saved.date }, orderBy: { id: "desc" } });
      await ensureSessionPlanningWindow(tx, revision.effectiveAt);
    }
    return saved;
  });
}
export async function removeProgramCalendar(
  db: DomainDb,
  input: z.infer<typeof programCalendarRemove>,
) {
  return inTransaction(db, async (tx) => {
    await lockCalendarPolicy(tx, input.date);
    const current = await tx.programCalendarDay.findUnique({
      where: { date: input.date },
    });
    if (!current?.active || current.version !== input.expectedVersion)
      throw new TRPCError({
        code: "CONFLICT",
        message: "The tutoring notice changed. Reload before removing it.",
      });
    const saved = await tx.programCalendarDay.update({
      where: { date: input.date },
      data: { active: false, version: { increment: 1 } },
    });
    if (pauseMeaning(current) !== pauseMeaning(saved)) {
      const revision = await tx.programCalendarPolicyRevision.findFirstOrThrow({ where: { date: saved.date }, orderBy: { id: "desc" } });
      await ensureSessionPlanningWindow(tx, revision.effectiveAt);
    }
    return saved;
  });
}
