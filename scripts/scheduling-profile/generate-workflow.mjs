import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";
import { groupSlots, partitionStepName, prepareStepName, profileGroups } from "./group-plan.mjs";

const root = fileURLToPath(new URL("../../", import.meta.url));
const workerPath = ".github/workflows/scheduling-profile-worker.yml";
const expression = (/** @type {string} */ value) => "${{ " + value + " }}";
const input = (/** @type {string} */ value) => expression(`inputs.${value}`);

/** Static provider-visible steps let retries authenticate individual partitions
 * while GitHub creates only one check for each scenario group. */
export function workerDefinition() {
  const names = ["baseline", "candidate", "group", "campaign", "anchor", "node-image", "schema-manifest",
    "baseline-selection-path", "baseline-selection-file-sha256", "baseline-selection-source",
    "catalog-baseline", "catalog-selection-path", "catalog-selection-file-sha256", "catalog-selection-source"];
  const inputs = Object.fromEntries(names.map((name) => [name, { required: true, type: "string" }]));
  /** @type {Array<{name:string,id?:string,if?:string,run?:string,shell?:string,uses?:string,with?:Record<string,string|number|boolean>,"timeout-minutes"?:number,env?:Record<string,string|number>}>} */
  const steps = [
    { name: "Checkout immutable candidate control", uses: "actions/checkout@v4",
      with: { ref: input("candidate"), "persist-credentials": false } },
    { name: "Set up Node", uses: "actions/setup-node@v4", with: { "node-version": 22 } },
  ];
  for (const group of ["preflight", ...profileGroups()]) for (const slot of groupSlots(group)) {
    const id = `prepare_${slot.scenario.replaceAll("-", "_")}_${slot.mode}_${slot.partition}`;
    const env = { PROFILE_SCENARIO: slot.scenario, PROFILE_MODE: slot.mode,
      PROFILE_PARTITION_INDEX: slot.partition, PROFILE_PARTITION_COUNT: slot.partitionCount,
      PROFILE_SAMPLES: slot.samples,
      PROFILE_PARTITION_RUNNER_ID: expression(`github.run_id`)+"-"+expression(`github.run_attempt`)+`-${slot.scenario}-${slot.mode}-${slot.partition}`,
      ...(slot.scenario === "catalog" ? {
        BASELINE_SHA: input("catalog-baseline"),
        PROFILE_BASELINE_SELECTION_PATH: input("catalog-selection-path"),
        PROFILE_BASELINE_SELECTION_FILE_SHA256: input("catalog-selection-file-sha256"),
        PROFILE_BASELINE_SELECTION_SOURCE: input("catalog-selection-source"),
      } : {}),
    };
    steps.push({ name: prepareStepName(slot), id,
      if: expression(`!cancelled() && inputs.group == '${group}'`),
      "timeout-minutes": 9,
      env, run: "node scripts/scheduling-profile/resume-run.mjs prepare", shell: "bash" });
    steps.push({ name: partitionStepName(slot),
      if: expression(`!cancelled() && inputs.group == '${group}' && steps.${id}.outputs.should_run == 'true'`),
      "timeout-minutes": 9,
      uses: "./.github/actions/scheduling-profile-partition",
      env, with: { "postgres-container-id": expression("job.services.postgres.id") } });
  }
  return { name: "Scheduling profile group", on: { workflow_call: { inputs } },
    permissions: { contents: "read", actions: "read" },
    jobs: { measure: { "runs-on": "ubuntu-latest", "timeout-minutes": 120,
      services: { postgres: { image: expression("fromJSON(inputs.campaign).postgresImage"),
        env: { POSTGRES_USER: "postgres", POSTGRES_PASSWORD: "postgres", POSTGRES_DB: "shbs_performance_test" },
        ports: ["55439:5432"],
        options: '--health-cmd "pg_isready -U postgres -d shbs_performance_test" --health-interval 5s --health-timeout 5s --health-retries 10' } },
      env: { BASELINE_SHA: input("baseline"), CANDIDATE_SHA: input("candidate"),
        PROFILE_SCHEMA_MANIFEST: input("schema-manifest"),
        PROFILE_BASELINE_SELECTION_PATH: input("baseline-selection-path"),
        PROFILE_BASELINE_SELECTION_FILE_SHA256: input("baseline-selection-file-sha256"),
        PROFILE_BASELINE_SELECTION_SOURCE: input("baseline-selection-source"),
        PROFILE_CAMPAIGN: input("campaign"), PROFILE_ANCHOR: input("anchor"),
        PROFILE_NODE_IMAGE: input("node-image"), GH_TOKEN: expression("github.token") },
      steps } } };
}

export function renderWorker() {
  return "# Generated by scripts/scheduling-profile/generate-workflow.mjs; do not edit partition steps manually.\n" +
    yaml.dump(workerDefinition(), { noRefs: true, lineWidth: -1, noCompatMode: true });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  assert.ok(process.argv.length === 2 || process.argv[2] === "--check", "Use generate-workflow.mjs [--check]");
  const destination = resolve(root, workerPath), generated = renderWorker();
  if (process.argv[2] === "--check") assert.equal(readFileSync(destination, "utf8").replaceAll("\r\n", "\n"), generated, "Regenerate scheduling profile worker");
  else writeFileSync(destination, generated);
}
